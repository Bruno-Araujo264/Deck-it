-- Espelho da API: sem renomear, sem limpar. Aninhados em JSON; payload guarda o objeto original inteiro.
CREATE TABLE IF NOT EXISTS bronze.scryfall_cards (
  _row_id          BIGINT       NOT NULL AUTO_INCREMENT PRIMARY KEY,
  _load_id         VARCHAR(64)  NOT NULL,
  _ingested_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  _source_file     VARCHAR(512) NULL,
  _row_hash        CHAR(64)     NOT NULL,
  id               CHAR(36)     NOT NULL,
  oracle_id        CHAR(36)     NULL,
  name             VARCHAR(500) NULL,
  lang             VARCHAR(8)   NULL,
  released_at      VARCHAR(16)  NULL,
  layout           VARCHAR(32)  NULL,
  mana_cost        VARCHAR(100) NULL,
  cmc              DOUBLE       NULL,
  type_line        VARCHAR(255) NULL,
  oracle_text      TEXT         NULL,
  colors           JSON         NULL,
  color_identity   JSON         NULL,
  keywords         JSON         NULL,
  card_faces       JSON         NULL,
  image_uris       JSON         NULL,
  legalities       JSON         NULL,
  prices           JSON         NULL,
  `set`            VARCHAR(16)  NULL,
  set_name         VARCHAR(255) NULL,
  collector_number VARCHAR(32)  NULL,
  rarity           VARCHAR(16)  NULL,
  payload          JSON         NOT NULL,
  KEY idx_load (_load_id),
  KEY idx_id_hash (id, _row_hash)
);
